ImageChannel = Literal["tool_native", "user_fallback"]
IMAGE_CHANNELS: tuple[ImageChannel, ...] = ("tool_native", "user_fallback")

MESSAGE_LIMIT = 12
PNG_PATH_KEY = "mmi_png_path"
TR_RULESET = "inputs_v1"

SYSTEM_PROMPT = (
    "You are an operations assistant for a software team. You can fetch dashboard "
    "screenshots with fetch_screenshot and send reports with send_report. Send a report "
    "only when the user asks you to. Answer the user's question in one or two sentences."
)


