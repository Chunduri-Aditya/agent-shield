"""The static page: its data and its HTML agree with the tracked files they come from.

`site/data.json` and `site/index.html` are generated by `scripts/page/build.py`. The first test
fails when either file differs from a fresh build. The others check the data against sources
read here by separate code, and check the template and the script for hand typed numbers.
"""

from __future__ import annotations

import ast
import html
import json
import re
import shutil
from html.parser import HTMLParser
from pathlib import Path
from typing import Any

import pytest

from scripts.page import build
from tests.test_public_claims import BANNED

REPO = Path(__file__).resolve().parent.parent
DATA = REPO / "site" / "data.json"
INDEX = REPO / "site" / "index.html"
TEMPLATE = REPO / "scripts" / "page" / "template.html"
SCRIPT = REPO / "scripts" / "page" / "build.py"
RECORD = REPO / "results" / "s1_event" / "S1_event_counts.json"
ERRATUM = REPO / "docs" / "ERRATUM.md"

# Identifiers that may hold a digit in the template text and in the script's constants.
IDENTIFIER = re.compile(r"(?<![a-z0-9])(?:s1|tl[-_]?01|dw[-_]?01)(?![a-z0-9])", re.I)
# (string constant of build.py, why it may hold a digit). Short on purpose.
ALLOWED_DIGIT_CONSTANTS = (
    ("sha256", "the key name the data shape fixes for the file hash, and the hash algorithm"),
)


def _data() -> dict[str, Any]:
    loaded: dict[str, Any] = json.loads(DATA.read_text(encoding="utf-8"))
    return loaded


def _index() -> str:
    return INDEX.read_text(encoding="utf-8")


class _VisibleText(HTMLParser):
    """Text of a page without style and script content."""

    def __init__(self) -> None:
        super().__init__()
        self.parts: list[str] = []
        self._skip = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag in ("style", "script"):
            self._skip += 1

    def handle_endtag(self, tag: str) -> None:
        if tag in ("style", "script"):
            self._skip -= 1

    def handle_data(self, data: str) -> None:
        if not self._skip:
            self.parts.append(data)


def _template_text() -> str:
    parser = _VisibleText()
    parser.feed(TEMPLATE.read_text(encoding="utf-8"))
    return re.sub(r"\{\{.*?\}\}", " ", " ".join(parser.parts))


def _inline(text: str) -> str:
    """Own copy of the inline rule: code spans and strong text only, after escaping."""
    escaped = html.escape(text)
    escaped = re.sub(r"`([^`]+)`", r"<code>\1</code>", escaped)
    return re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", escaped)


def test_site_files_equal_a_fresh_build() -> None:
    data = build.collect(REPO)
    assert DATA.read_text(encoding="utf-8") == build.dumps(data)
    template = TEMPLATE.read_text(encoding="utf-8")
    assert INDEX.read_text(encoding="utf-8") == build.render(data, template)


def test_site_holds_exactly_the_two_generated_files() -> None:
    assert sorted(p.name for p in (REPO / "site").iterdir()) == ["data.json", "index.html"]


def test_senders_show_their_declined_counts() -> None:
    # Literal quoted from showcase/S1_EVENT_FINDING.md: claude-opus-5-5 declined 236 of 240.
    assert "claude-opus-5-5: 4 of 4 answered samples, 236 of 240 declined" in _index()


def test_s1_counts_match_the_record_read_here() -> None:
    record = json.loads(RECORD.read_text(encoding="utf-8"))["models"]
    models = {m["model"]: m for m in _data()["s1"]["models"]}
    assert set(models) == set(record)
    for name, per_task in record.items():
        assert models[name]["answered"] == sum(pair[0] for pair in per_task.values())
        assert models[name]["sent"] == sum(pair[1] for pair in per_task.values())
    # Literals quoted from showcase/S1_EVENT_FINDING.md.
    assert (models["claude-sonnet-5-5"]["answered"], models["claude-sonnet-5-5"]["sent"]) == (
        239,
        54,
    )
    assert _data()["s1"]["models_without_sends"] == 9
    assert _data()["s1"]["models_with_sends"] == 4


def test_erratum_rows_are_all_on_the_page() -> None:
    erratum = _data()["erratum"]
    found = re.findall(r"^\| (W\d+) \|", ERRATUM.read_text(encoding="utf-8"), re.M)
    assert len(erratum["rows"]) == len(found) == erratum["count"]
    assert [r["id"] for r in erratum["rows"]] == [f"W{k}" for k in range(1, len(found) + 1)]
    page = _index()
    for row in erratum["rows"]:
        assert _inline(row["claim"]) in page, row["id"]


